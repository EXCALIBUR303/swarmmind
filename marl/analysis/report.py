"""`docs/RESULTS.md` generator (§34: results are produced only by scripts;
this file is never hand-edited). Everything shown comes from `summary.json`."""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

from marl.analysis.aggregate import LABELS

TABLE_METRICS = [
    ("success_rate", "Success", 2),
    ("censored_steps", "Censored steps", 1),
    ("steps_on_success", "Steps (successes)", 1),
    ("coverage", "Coverage", 2),
    ("collisions_per_100_agent_steps", "Collisions /100 agent-steps", 2),
    ("return_mean", "Return", 2),
]
COMPARE_METRICS = ["success_rate", "censored_steps", "coverage", "collisions_per_100_agent_steps"]
COORD_TABLE_METRICS = [
    ("der", "DER", 3),
    ("der_at_50", "DER@50", 3),
    ("der_iso", "DER (isolation null)", 3),
    ("visitation_overlap", "Visitation overlap", 3),
    ("redundant_pursuit", "Redundant pursuit", 2),
    ("allocation_optimality", "Allocation optimality", 2),
    ("mean_inter_robot_distance", "Mean inter-robot dist.", 2),
    ("dispersion_speed", "Dispersion speed (steps)", 1),
]


def _cell(iv: dict[str, Any] | None, nd: int) -> str:
    if not iv:
        return "—"
    if iv["lo"] is None:
        return f"{iv['mean']:.{nd}f} (n={iv['n']})"
    return f"{iv['mean']:.{nd}f} [{iv['lo']:.{nd}f}, {iv['hi']:.{nd}f}]"


def _method_table(methods: dict[str, Any], split: str, mode: str) -> list[str]:
    rows = []
    for m in ("random", "heuristic", "ippo", "mappo"):
        blk = methods.get(m, {}).get("splits", {}).get(split, {}).get(mode)
        if not blk:
            continue
        name = LABELS[m] + (" (reference)" if m == "heuristic" else "")
        rows.append(f"| {name} | {blk['n_seeds']} | " + " | ".join(
            _cell(blk[k]["interval"], nd) for k, _, nd in TABLE_METRICS) + " |")
    if not rows:
        return []
    head = "| Method | Seeds | " + " | ".join(label for _, label, _ in TABLE_METRICS) + " |"
    return [head, "|" + "---|" * (len(TABLE_METRICS) + 2), *rows]


def _diff_cell(d: dict[str, Any] | None) -> str:
    if not d:
        return "—"
    g = "n/a" if d["hedges_g"] is None else f"{d['hedges_g']:+.2f}"
    if d["lo"] is None:
        return f"{d['diff']:+.3f} (CI undefined; g {g})"
    pv = d["p_value"]
    p = "" if pv is None else (", p<0.001" if pv < 0.001 else f", p={pv:.3f}")
    return f"{d['diff']:+.3f} [{d['lo']:+.3f}, {d['hi']:+.3f}]{p}, g {g}"


def _coordination_table(coord: dict[str, Any]) -> list[str]:
    rows = []
    for m in ("random", "ippo", "mappo"):
        blk = coord["methods"].get(m)
        if not blk:
            continue
        rows.append(f"| {LABELS[m]} | {blk['n_seeds']} | " + " | ".join(
            _cell(blk.get(k), nd) for k, _, nd in COORD_TABLE_METRICS) + " |")
    if not rows:
        return []
    head = "| Method | Seeds | " + " | ".join(label for _, label, _ in COORD_TABLE_METRICS) + " |"
    return [head, "|" + "---|" * (len(COORD_TABLE_METRICS) + 2), *rows]


def _h3_criteria_table(h3: dict[str, Any]) -> list[str]:
    per_algo = h3.get("per_algo")
    if not per_algo:
        return []
    rows = ["| Criterion (§24.4) | " + " | ".join(LABELS[a] for a in per_algo) + " |",
            "|" + "---|" * (len(per_algo) + 1)]
    labels = [
        ("h1_supported", "1. H1 supported"),
        ("der50_lower_than_random", "2a. DER@50 < Random"),
        ("der50_lower_than_isolation_null", "2b. DER@50 < isolation null"),
        ("redundant_pursuit_lower_than_random", "3. Redundant pursuit < Random"),
        ("ablation_degrades_coordination", "4. Ablation degrades coordination"),
    ]
    for key, label in labels:
        rows.append(f"| {label} | " + " | ".join(
            "✅" if v["criteria"].get(key) else "❌" for v in per_algo.values()) + " |")
    rows.append("| **Coordination emerged** | " + " | ".join(
        "**✅**" if v["coordination_emerged"] else "**❌**" for v in per_algo.values()) + " |")
    return rows


def render_results_md(summary: dict[str, Any], figures: list[Path], md_path: Path) -> str:
    lines: list[str] = []
    eval_seeds = ", ".join(str(i) for i in range(summary["config"]["final_eval"]["episodes_per_map"]))
    title = f"# SWARMMIND results — study `{summary['study']}`"
    lines += [title, ""]
    if summary["smoke"]:
        lines += ["> **SMOKE STUDY — infrastructure dry run. These numbers are NOT evidence for any hypothesis;",
                  "> they only show that training → held-out evaluation → aggregation → reporting runs end to end.**",
                  ""]
    lines += [
        f"*Generated by `scripts/aggregate_results.py` at {summary['generated']} from "
        f"`results/studies/{summary['study']}/summary.json`. Do not edit by hand (§34).*",
        "",
        "**Protocol.** Unit of analysis: one training seed (learned) or one evaluation sampling seed (Random). "
        "Each seed's value is the mean over its held-out episodes (every map × evaluation seeds "
        f"{{{eval_seeds}}}), final checkpoint, stochastic policy (greedy is secondary). "
        "Intervals are 95% t-intervals over seeds; "
        "differences use Welch 95% CIs with Hedges' g. With few seeds, a CI that includes 0 means "
        "*no detectable difference*, never equivalence. t-intervals are reported as computed, not "
        "clipped to a metric's range, so with few seeds a success-rate interval can extend past 0 or 1.",
        "",
    ]
    if summary["missing"]:
        lines += ["**Missing / incomplete:**", "", *[f"- {m}" for m in summary["missing"]], ""]

    for level, data in summary["levels"].items():
        methods, comps, hyp = data["methods"], data["comparisons"], data["hypotheses"]
        lines += [f"## Level {level}", "", "### Hypotheses (§4, decided mechanically)", ""]
        for h in ("H1", "H2", "H3", "H4"):
            if h not in hyp:
                continue
            if h == "H1":
                lines += [f"- {v['statement']}" for v in hyp[h].values()]
            else:
                lines.append(f"- {hyp[h]['statement']}")
        lines.append("")
        if "coordination" in data:
            coord_table = _coordination_table(data["coordination"])
            criteria_table = _h3_criteria_table(hyp.get("H3", {}))
            if coord_table:
                proto = data["coordination"].get("protocol", {})
                lines += [f"### Coordination analysis (§24) — {proto.get('n_maps', '?')} maps × eval seeds "
                          f"{proto.get('eval_seeds', [])}", "", *coord_table, ""]
            if criteria_table:
                lines += ["**§24.4 coordination-emergence criteria**", "", *criteria_table, ""]
        for split in summary["config"]["final_eval"]["map_sets"]:
            for mode in ("stochastic", "greedy"):
                table = _method_table(methods, split, mode)
                if table:
                    tag = "primary" if (split, mode) == ("test", "stochastic") else "secondary"
                    lines += [f"### {split.capitalize()} maps — {mode} ({tag})", "", *table, ""]
            for mode in ("stochastic", "greedy"):
                comp = comps.get(f"{split}/{mode}")
                if not comp:
                    continue
                lines += [f"**Differences, {split} / {mode}** (A − B, Welch 95% CI, Hedges' g)", "",
                          "| Comparison | " + " | ".join(COMPARE_METRICS) + " |",
                          "|" + "---|" * (len(COMPARE_METRICS) + 1)]
                for name, per_metric in comp.items():
                    a, b = name.split("-")
                    lines.append(f"| {LABELS[a]} − {LABELS[b]} | "
                                 + " | ".join(_diff_cell(per_metric.get(m)) for m in COMPARE_METRICS) + " |")
                lines.append("")
        cur = {a: methods.get(a, {}).get("validation_curve") for a in ("ippo", "mappo")}
        if any(cur.values()):
            lines += ["### Training (validation maps)", "",
                      "| Method | Untrained (step 0) success | Final validation success | Validation-success AUC |",
                      "|---|---|---|---|"]
            for a, c in cur.items():
                if c:
                    lines.append(f"| {LABELS[a]} | {_cell(c['untrained_val_success'], 2)} | "
                                 f"{_cell(c['final_val_success'], 2)} | {_cell(c['auc'], 3)} |")
            if "validation_auc" in comps:
                lines.append(f"\nMAPPO − IPPO validation AUC: {_diff_cell(comps['validation_auc']['mappo-ippo'])}")
            lines.append("")
        figs = [f for f in figures if f.name.startswith(f"{level}_")]
        if figs:
            lines += ["### Figures", ""]
            lines += [f"![{f.stem}]({os.path.relpath(f, md_path.parent)})" for f in figs]
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"
