"""Frozen eval set generation/loading and isolation guard tests (§20.3, §33.4)."""

from __future__ import annotations

from marl.envs.core.config import EnvConfig
from marl.evaluation.eval_sets import (
    TEST_SEED_BASE,
    VALIDATION_SEED_BASE,
    eval_set_exists,
    frozen_hash_manifest,
    generate_test_maps,
    generate_validation_maps,
    is_eval_map,
    load_eval_set,
    save_eval_set,
)


def _cfg(**overrides) -> EnvConfig:
    base = dict(
        name="t",
        width=8,
        height=8,
        n_robots=2,
        n_targets=1,
        obstacle_density=0.1,
        max_steps=60,
        sensor_radius=2.0,
        obs_radius=5,
    )
    base.update(overrides)
    return EnvConfig.model_validate(base)


def test_validation_and_test_use_disjoint_seed_bases():
    cfg = _cfg()
    val_maps = generate_validation_maps(cfg, n=5)
    test_maps = generate_test_maps(cfg, n=5)
    val_hashes = {m.content_hash for m in val_maps}
    test_hashes = {m.content_hash for m in test_maps}
    assert val_hashes.isdisjoint(test_hashes)


def test_validation_maps_deterministic():
    cfg = _cfg()
    a = generate_validation_maps(cfg, n=5)
    b = generate_validation_maps(cfg, n=5)
    assert [m.content_hash for m in a] == [m.content_hash for m in b]


def test_seed_bases_are_the_spec_values():
    assert VALIDATION_SEED_BASE == 1_000_000
    assert TEST_SEED_BASE == 2_000_000


def test_save_and_load_eval_set_roundtrip(tmp_path):
    cfg = _cfg()
    maps = generate_validation_maps(cfg, n=5)
    save_eval_set(maps, "TX", "validation", base_dir=tmp_path)
    assert eval_set_exists("TX", "validation", base_dir=tmp_path)
    loaded = load_eval_set("TX", "validation", base_dir=tmp_path)
    assert len(loaded) == 5
    assert [m.content_hash for m in loaded] == [m.content_hash for m in maps]


def test_load_missing_eval_set_raises(tmp_path):
    import pytest

    with pytest.raises(FileNotFoundError):
        load_eval_set("NOPE", "validation", base_dir=tmp_path)


def test_frozen_hash_manifest_and_is_eval_map(tmp_path):
    cfg = _cfg()
    val_maps = generate_validation_maps(cfg, n=5)
    test_maps = generate_test_maps(cfg, n=5)
    save_eval_set(val_maps, "TX", "validation", base_dir=tmp_path)
    save_eval_set(test_maps, "TX", "test", base_dir=tmp_path)

    manifest = frozen_hash_manifest(["TX"], base_dir=tmp_path)
    assert len(manifest) == 10
    assert is_eval_map(val_maps[0], manifest)
    assert is_eval_map(test_maps[0], manifest)

    from marl.envs.core.mapgen import generate_map

    training_map = generate_map(cfg, seed=42)  # a normal small training seed
    assert not is_eval_map(training_map, manifest)


def test_frozen_manifest_skips_levels_without_files(tmp_path):
    manifest = frozen_hash_manifest(["NONEXISTENT"], base_dir=tmp_path)
    assert manifest == set()


def test_real_frozen_eval_sets_exist_for_all_levels():
    """The actual committed eval sets (generated by scripts/make_eval_maps.py)
    must exist for every level and contain the expected counts."""
    for level in ("L1", "L2", "L3", "L4"):
        assert eval_set_exists(level, "validation"), f"missing validation set for {level}"
        assert eval_set_exists(level, "test"), f"missing test set for {level}"
        val = load_eval_set(level, "validation")
        test = load_eval_set(level, "test")
        assert len(val) == 50
        assert len(test) == 100
        assert {m.content_hash for m in val}.isdisjoint({m.content_hash for m in test})


# --- Phase 6: structured split (G2), map validation, file-level immutability ---


def test_validate_map_spec_accepts_generated_maps_and_rejects_bad_ones():
    from marl.envs.core.mapgen import validate_map_spec
    from marl.envs.core.maps_io import MapSpec

    cfg = _cfg()
    for m in generate_validation_maps(cfg, n=5):
        assert validate_map_spec(m, cfg) == []

    rows = ["........"] * 8
    good = MapSpec(id="g", width=8, height=8, terrain_rows=rows, robot_starts=[(0, 0), (0, 1)], targets=[(7, 7)])
    assert validate_map_spec(good, cfg) == []

    too_close = MapSpec(id="c", width=8, height=8, terrain_rows=rows, robot_starts=[(0, 0), (0, 1)], targets=[(0, 3)])
    assert any("BFS distance" in p for p in validate_map_spec(too_close, cfg))

    walled = ["........"] * 4 + ["########"] + ["........"] * 3
    split = MapSpec(id="w", width=8, height=8, terrain_rows=walled, robot_starts=[(0, 0), (0, 1)], targets=[(7, 7)])
    problems = validate_map_spec(split, cfg)
    assert any("disconnected" in p for p in problems) and any("unreachable" in p for p in problems)

    wrong_count = MapSpec(id="n", width=8, height=8, terrain_rows=rows, robot_starts=[(0, 0)], targets=[(7, 7)])
    assert any("robot starts" in p for p in validate_map_spec(wrong_count, cfg))

    on_wall = MapSpec(id="o", width=8, height=8, terrain_rows=walled, robot_starts=[(4, 0), (0, 1)], targets=[(7, 7)])
    assert any("not a free cell" in p for p in validate_map_spec(on_wall, cfg))


def test_frozen_structured_set_matches_its_txt_sources_and_is_valid():
    """The committed structured/L2.json must be exactly what the .txt
    sources produce today (no silent edits to either), and every map passes
    the procedural generator's guarantees for L2."""
    from marl.envs.core.config import LevelRegistry
    from marl.evaluation.eval_sets import build_structured_set

    cfg = LevelRegistry().get("L2")
    rebuilt = build_structured_set(cfg, "L2")
    frozen = load_eval_set("L2", "structured")
    assert 10 <= len(frozen) <= 20  # §20.3
    assert [m.content_hash for m in rebuilt] == [m.content_hash for m in frozen]
    assert len({m.content_hash for m in frozen}) == len(frozen)


def test_structured_maps_are_in_the_training_isolation_guard():
    from marl.envs.core.config import LevelRegistry

    guard = frozen_hash_manifest(LevelRegistry().available_levels())
    assert all(m.content_hash in guard for m in load_eval_set("L2", "structured"))


def test_frozen_map_files_match_committed_manifest():
    """§33.4 eval-set immutability: every frozen JSON file's sha256 equals
    the committed configs/maps/manifest.json (and nothing is missing/extra)."""
    import json

    from marl.evaluation.eval_sets import MANIFEST_NAME, compute_maps_manifest
    from marl.utils.paths import MAPS_DIR

    recorded = json.loads((MAPS_DIR / MANIFEST_NAME).read_text())
    assert compute_maps_manifest() == recorded
