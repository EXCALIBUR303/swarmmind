#!/usr/bin/env python
"""Export the API contract for the frontend (§28, Phase 10).

Writes:
  docs/openapi.json                    OpenAPI 3 schema of every REST route
  docs/schemas/replay.schema.json      JSON Schema of `marl.replay.schema.Replay`
  docs/schemas/ws_messages.schema.json JSON Schema of the WebSocket messages
  docs/API.md                          human-readable reference generated from the OpenAPI

Phase 11 generates `frontend/src/api/types.gen.ts` from these files.

Usage:  python scripts/export_schemas.py [--check]
  --check  exit 1 if the files on disk differ from what would be generated
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from pydantic import TypeAdapter

from backend.app.main import create_app
from backend.app.schemas.sessions import (
    WsCommand,
    WsEpisodeEnd,
    WsError,
    WsFrameMessage,
    WsStateMessage,
)
from marl.replay.schema import Replay
from marl.utils.paths import DOCS_DIR

TRAINING_WS = {
    "update": "one `metrics.jsonl` row: `{type, update, env_steps, agent_steps, mean_reward, explained_variance, policy_loss, value_loss, entropy, approx_kl, clip_fraction, ...}`",
    "val_eval": "one `eval_val.jsonl` row: `{type, update, env_steps, success_rate, mean_return, mean_coverage, mean_steps_on_success, censored_mean_steps}`",
    "status": "`{type: 'status', status: running|completed|failed|interrupted|invalid}` on every change",
    "end": "`{type: 'end', status}` after the run reaches a terminal status and its files are drained; the server then closes with 1000",
}

NOTES = """\
# SWARMMIND API

Generated by `scripts/export_schemas.py` from the FastAPI app's OpenAPI schema
(`docs/openapi.json`). Do not edit by hand; edit the routers/schemas and re-run.

**Base URL:** `http://127.0.0.1:8000` (localhost only). REST under `/api`, WebSockets under `/ws`.
Interactive docs while the server runs: `/docs`.

## Conventions

- **IDs** (`run_id`, `replay_id`, `model_id`, `map_id`, `session_id`, `job_id`, `study`) match
  `^[A-Za-z0-9_-][A-Za-z0-9._-]{0,127}$`. Anything else is `422` (path/query) or WS close `4404`.
- **Errors:** `{"detail": "<message>"}` (or FastAPI's validation list on `422`). `404` unknown id,
  `409` conflict (episode finished / job already finished / job slot taken), `422` invalid input,
  `429` too many live sessions. Messages never contain filesystem paths.
- **Run ids.** Pipeline runs are named `s<seed>-<timestamp>-<hash8>` and unique. Early pilot runs were all
  named `seed0`; when run directory names collide every colliding run is addressed as
  `<study>.<algo>.<level>.<name>`.
- **Models** are the `actor.pt` exports of *completed* runs (and `models/<name>/actor.pt`).
  A model id equals its run id. Actors are loaded with `weights_only=True`; no critic is ever loaded.
- **Frames** in live sessions are exactly the replay frame type (`marl.replay.schema.ReplayFrame`),
  produced by the same code path (`marl.replay.recorder.build_frame`) — a live session is byte-identical
  to the recorded replay of the same inputs (tested against a stored study replay).
- **Initial state.** The first sensing pass happens at reset and is *not* in any frame's `newly_known`.
  Sessions expose it as `initial.known_team`; for replays use `GET /api/replays/{id}/initial` (recorded when the replay
  has `initial`, otherwise derived by re-running reset on the replay's own map — study replays from Phases 3–8 predate
  the field). Reconstruct the known map as `initial.known_team ∪ ⋃_{i<=t} frames[i].newly_known`; skipping the initial
  cells leaves the start area fogged for the whole replay.
- **Seeds.** `seed` generates the map when it is procedural and always seeds the policy's sampling stream:
  `numpy.default_rng(episode_seed(map_id, seed))`, i.e. the batch evaluator's `eval_seed` stream (§28.4).
- **Held-out maps.** `GET /api/maps?set=test|structured` and fixed-map sessions on those sets go through
  the held-out gatekeeper and append to `results/heldout_access_log.jsonl`.
- **Heatmaps** were precomputed per *(study, level, algo, map)* aggregated over the study's seeds, so
  `/api/analysis/{study}/heatmap` is keyed by study, not by run as the original spec sketched.
- **Eval results** omit per-episode records unless `?episodes=true`.
- **No local paths.** Absolute repo/home paths inside stored manifests and summaries are rewritten to
  repo-relative paths (or `~/`) before being returned.
- **JSON only.** POST bodies must be `application/json` (anything else is `422`), and CORS admits only the
  configured dev origin, so a foreign web page cannot drive the API. The `Host` header is allow-listed
  (`localhost`, `127.0.0.1`) against DNS rebinding.
- **Replay caching.** `GET /api/replays/{id}` sends `Cache-Control: no-cache` plus an ETag; all other responses are `no-store`.
- **Run it with** `uvicorn backend.app.main:app --host 127.0.0.1 --port 8000 --ws-max-size 65536`
  (the flag bounds WebSocket message size at the protocol layer).

## WebSocket: simulation — `WS /ws/sessions/{session_id}`

The server owns the clock. At 1× it advances 4 steps/s; `speed` ∈ [0.25, 8]; never more than 30 steps/s.
A browser `Origin` other than the configured dev origin is refused (`4403`); an unknown/expired session closes `4404`.
On connect the server sends a `state` message so a reconnecting client can resync.
One connection drives a session at a time: a new connection takes over and the previous one is closed with `4409`.
REST `POST /sessions/{id}/step` is for clients that do not use the WebSocket; mixing it with a playing
WebSocket makes the stream skip the steps the REST call consumed.

Client → server (`WsCommand`): `{"cmd": "play"|"pause"|"step"|"reset"|"speed", "value"?: ...}`
- `step`: `value` = n ∈ [1, 50] (default 1); refused while playing.
- `reset`: `value` = optional `{seed?, map?}` (same as `POST /sessions/{id}/reset`); pauses first.
- `speed`: `value` ∈ [0.25, 8].
- Strict typing: `true`/strings are not accepted as numbers. Messages > 4 KiB are rejected.

Server → client: `state`, `frame`, `episode_end`, `error` (schemas in `docs/schemas/ws_messages.schema.json`).
Errors never close the connection. `pause` completes the in-flight step first, so the client has seen
every step the server has taken.

## WebSocket: training — `WS /ws/training/{run_id}?from_update=0`

Tails the run's `metrics.jsonl` and `eval_val.jsonl` (complete lines only) and pushes:
""" + "\n".join(f"- `{k}`: {v}" for k, v in TRAINING_WS.items()) + """

Polling fallback: `GET /api/experiments/{run_id}/metrics?from_update=`.

## Training jobs

`POST /api/training/jobs` launches `scripts/train.py` as a **subprocess** (never in the API process; argv list,
no shell) with study `ui`. Parameters are bounded: `total_env_steps` ∈ [2048, 10 000 000]; `overrides` limited
to the allowlist in `backend/app/schemas/training.py`. At most one job runs at a time (`409` otherwise).
`cancel` sends SIGTERM (the trainer writes `interrupted` to its manifest) and escalates to SIGKILL after 15 s.

---

# REST reference
"""


def build_openapi() -> dict:
    return create_app().openapi()


def render_api_md(spec: dict) -> str:
    out = [NOTES]
    by_tag: dict[str, list[tuple[str, str, dict]]] = {}
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            by_tag.setdefault((op.get("tags") or ["other"])[0], []).append((method.upper(), path, op))
    for tag in sorted(by_tag):
        out.append(f"\n## {tag}\n")
        out.append("| Method | Path | Summary | Success |\n|---|---|---|---|")
        for method, path, op in sorted(by_tag[tag], key=lambda t: (t[1], t[0])):
            ok = next((c for c in op["responses"] if c.startswith("2")), "?")
            summary = (op.get("summary") or "").replace("|", "\\|")
            out.append(f"| {method} | `{path}` | {summary} | {ok} |")
        for method, path, op in sorted(by_tag[tag], key=lambda t: (t[1], t[0])):
            doc = (op.get("description") or "").strip().split("\n\n")[0].replace("\n", " ")
            params = [p for p in op.get("parameters", [])]
            if doc or params:
                out.append(f"\n### `{method} {path}`\n")
                if doc:
                    out.append(doc + "\n")
                if params:
                    out.append("Parameters: " + ", ".join(
                        f"`{p['name']}` ({p['in']}{', required' if p.get('required') else ''})" for p in params
                    ) + "\n")
    return "\n".join(out) + "\n"


def ws_schema() -> dict:
    msgs = [WsCommand, WsStateMessage, WsFrameMessage, WsEpisodeEnd, WsError]
    defs: dict = {}
    props: dict = {}
    for m in msgs:
        s = m.model_json_schema(ref_template="#/$defs/{model}")
        defs.update(s.pop("$defs", {}))
        props[m.__name__] = s
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", "title": "SWARMMIND WebSocket messages", "$defs": {**defs, **props}}


def outputs() -> dict[Path, str]:
    spec = build_openapi()
    j = lambda o: json.dumps(o, indent=2, sort_keys=True) + "\n"  # noqa: E731
    return {
        DOCS_DIR / "openapi.json": j(spec),
        DOCS_DIR / "schemas" / "replay.schema.json": j(TypeAdapter(Replay).json_schema()),
        DOCS_DIR / "schemas" / "ws_messages.schema.json": j(ws_schema()),
        DOCS_DIR / "API.md": render_api_md(spec),
    }


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    stale = []
    for path, text in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(DOCS_DIR.parent)}")
    if stale:
        print("stale (run scripts/export_schemas.py):", *[str(s) for s in stale], sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
