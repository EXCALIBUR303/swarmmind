"""Render the step log written by scripts/fresh_clone_check.sh into docs/FRESH_CLONE_REPORT.md.

usage: fresh_clone_report.py STEPS_TSV OUT_MD "<source description>"
Each TSV row: name <TAB> command <TAB> exit code <TAB> seconds (commands are flattened to one line)."""

import re
import sys
import time
from pathlib import Path

log, out, mode = sys.argv[1:4]
rows = []
for line in Path(log).read_text().split("\n"):
    parts = line.split("\t")
    if len(parts) == 4 and re.fullmatch(r"\d+", parts[3]):
        rows.append(parts)
    elif rows and line.strip() and len(parts) == 1 and not re.fullmatch(r"\d+ .*", line):
        pass  # continuation of a multi-line command from older logs
lines = ["# Fresh-clone report", "",
         f"Generated by `scripts/fresh_clone_check.sh` on {time.strftime('%Y-%m-%d %H:%M:%S')}. Do not edit by hand.", "",
         f"**Source:** {mode}", "",
         "Every step ran in a new directory, with a new virtualenv and a new `node_modules`, following the README quickstart. "
         "Package downloads came from warm local caches on this run, so step 1's time understates a cold install.", "",
         "| Step | Command | Exit | Seconds |", "|---|---|---|---|"]
ok = True
for name, cmd, rc, sec in rows:
    ok &= rc == "0"
    short = re.sub(r"\s+", " ", cmd).replace("|", "/")
    short = re.sub(r"/var/folders/\S+/(sm_fresh\S*)/", "<tmp>/", short)[:70]
    lines.append(f"| {name} | `{short}` | {'**0**' if rc == '0' else '**FAIL ' + rc + '**'} | {sec} |")
lines += ["", f"**Overall: {'PASS' if ok else 'FAIL'}** — {len(rows)} steps, total {sum(int(r[3]) for r in rows)} s."]
Path(out).write_text("\n".join(lines) + "\n")
print("\n".join(lines))
sys.exit(0 if ok else 1)
